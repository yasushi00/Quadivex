import assert from 'node:assert/strict';
import fs from 'node:fs';
import {Board,Move,Position} from '../keishi_rules.js';
import {exportKjf} from '../kjf_export.js';
const at = s => (Number(s[1])-1)*5+Number(s[0])-1;
const mk = a=>a.reduce((m,v)=>m|(1<<at(v)),0);
const Black=['11','12','21','32'],White=['33','34','43','55'];
const orders={B:Black.map(at),W:White.map(at)};
const board=(B,W)=>{const b=new Board();b.reset_with(mk(B),mk(W));return b;};
const first=board(Black,White);
const fb=first.clone_js();fb.do_move(new Move(new Position(3-1,2-1),new Position(2-1,2-1)));
assert.equal(fb.is_square(0),true);
const second=board(White,Black);second.turn=1;
const sb=second.clone_js();sb.do_move(new Move(new Position(3-1,2-1),new Position(2-1,2-1)));
assert.equal(sb.is_square(1),true);
const p={p1:{name:'QuadZenith',type:'engine',engine:{version:'1.0.0',level:8}},p2:{name:'Rust7',type:'engine',engine:{level:7}}};
const a={snapshots:[first,fb],stoneOrders:orders,reason:'square',winner:0,startingColor:'B'};
const b={snapshots:[second,sb],stoneOrders:{B:orders.W,W:orders.B},reason:'square',winner:1,startingColor:'W'};
const doc=exportKjf({first:a,second:b,players:p});
assert.equal(doc.format,'KJF');assert.equal(doc.version,'1.0');
assert.equal(doc.header.matchType,'two-game');assert.equal(doc.header.rules,'jun-keishi');
assert.deepEqual(doc.games[0].initial.board.B,Black);
assert.deepEqual(doc.games[1].initial.board.W,Black);
assert.deepEqual(doc.games[1].initial.board.B,White);
assert.deepEqual(doc.games[0].moves[0].board.B,['11','12','21','22']);
assert.deepEqual(doc.games[1].moves[0].board.W,['11','12','21','22']);
assert.deepEqual(doc.games.map(g=>g.initial.first),['B','W']);
assert.deepEqual(doc.games.map(g=>g.result.winner),['p1','p2']);
assert.deepEqual(doc.result,{status:'finished',winner:null,reason:'split'});
// No premature game 2 after evaluation cutoff.
const interrupted={...a,snapshots:[first],reason:'maxPly',winner:null};
const cut=exportKjf({first:interrupted,players:p});
assert.equal(cut.games.length,1);assert.deepEqual(cut.result,{status:'interrupted',winner:null,reason:'interrupted'});
assert.throws(()=>exportKjf({first:interrupted,second:b,players:p}),/Cannot export/);
const single=exportKjf({first:{...a,matchType:'single'},players:p,matchType:'single'});
assert.deepEqual(single.result,{status:'finished',winner:'p1',reason:'single_game'});
const ongoing=exportKjf({first:{snapshots:[first],stoneOrders:orders,reason:'playing',matchType:'single'},players:p,matchType:'single'});
assert.deepEqual(ongoing.result,{status:'playing',winner:null,reason:null});
const bad={...b,stoneOrders:{B:orders.B,W:orders.W}};
assert.throws(()=>exportKjf({first:a,second:bad,players:p}),/Order mismatch/);
console.log('PASS: KJF 1.0 two-game, positions, color swap, move identity, outcomes, interrupted, single');
